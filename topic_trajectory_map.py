#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""Create Topic Trajectory Maps from patent_bertopic_results.xlsx.

Expected sheets generated by patent_bertopic.py:
  - Topic History
  - Weak Signal Ranking

Outputs:
  - topic_trajectory_map.html       interactive trajectories
  - topic_trajectory_animation.html animated year-by-year map
  - topic_trajectory_map.png        static trajectories
  - topic_trajectory_data.xlsx      processed plotting data

Example:
  python topic_trajectory_map.py --input patent_bertopic_results.xlsx
  python topic_trajectory_map.py --input patent_bertopic_results.xlsx --top-n 15 --label-top-n 10
"""
from __future__ import annotations

import argparse
from pathlib import Path
import warnings

import numpy as np
import pandas as pd


def parse_args():
    p = argparse.ArgumentParser(description="Create Topic Trajectory Maps from BERTopic results Excel")
    p.add_argument("--input", default="patent_bertopic_results.xlsx")
    p.add_argument("--history-sheet", default="Topic History")
    p.add_argument("--ranking-sheet", default="Weak Signal Ranking")
    p.add_argument("--year-column", default="application_year")
    p.add_argument("--top-n", type=int, default=20,
                   help="Number of topics to draw. Selected by ranking if available.")
    p.add_argument("--label-top-n", type=int, default=10,
                   help="Number of highest-ranked topics labeled on the static map.")
    p.add_argument("--min-total-count", type=int, default=3)
    p.add_argument("--tail-years", type=int, default=0,
                   help="Use only the latest N years. 0 means all years.")
    p.add_argument("--growth-clip-low", type=float, default=0.02,
                   help="Lower quantile for clipping growth values.")
    p.add_argument("--growth-clip-high", type=float, default=0.98,
                   help="Upper quantile for clipping growth values.")
    p.add_argument("--html", default="topic_trajectory_map.html")
    p.add_argument("--animation-html", default="topic_trajectory_animation.html")
    p.add_argument("--png", default="topic_trajectory_map.png")
    p.add_argument("--data-output", default="topic_trajectory_data.xlsx")
    p.add_argument("--no-animation", action="store_true")
    return p.parse_args()


def find_year_column(history: pd.DataFrame, requested: str) -> str:
    if requested in history.columns:
        return requested
    candidates = ["application_year", "filing_year", "publication_year", "year", "Year"]
    for c in candidates:
        if c in history.columns:
            return c
    raise ValueError(f"Year column not found. Available columns: {list(history.columns)}")


def load_results(args):
    path = Path(args.input)
    if not path.exists():
        raise FileNotFoundError(f"Input file not found: {path}")

    xl = pd.ExcelFile(path, engine="openpyxl")
    if args.history_sheet not in xl.sheet_names:
        raise ValueError(f"Sheet '{args.history_sheet}' not found. Available: {xl.sheet_names}")

    history = pd.read_excel(path, sheet_name=args.history_sheet, engine="openpyxl")
    ranking = None
    if args.ranking_sheet in xl.sheet_names:
        ranking = pd.read_excel(path, sheet_name=args.ranking_sheet, engine="openpyxl")

    year_col = find_year_column(history, args.year_column)
    required = {"topic", "topic_count", "share"}
    missing = required - set(history.columns)
    if missing:
        raise ValueError(f"Topic History is missing columns: {sorted(missing)}")

    history[year_col] = pd.to_numeric(history[year_col], errors="coerce")
    history["topic"] = pd.to_numeric(history["topic"], errors="coerce")
    history["topic_count"] = pd.to_numeric(history["topic_count"], errors="coerce").fillna(0)
    history["share"] = pd.to_numeric(history["share"], errors="coerce").fillna(0.0)
    history = history.dropna(subset=[year_col, "topic"]).copy()
    history[year_col] = history[year_col].astype(int)
    history["topic"] = history["topic"].astype(int)
    history = history[history["topic"] != -1].copy()

    if "rolling_growth" not in history.columns:
        history = history.sort_values(["topic", year_col])
        if "rolling_share" not in history.columns:
            history["rolling_share"] = history.groupby("topic")["share"].transform(
                lambda s: s.rolling(3, min_periods=1).mean()
            )
        eps = 1e-6
        previous = history.groupby("topic")["rolling_share"].shift(1)
        history["rolling_growth"] = np.log(
            (history["rolling_share"] + eps) / (previous + eps)
        ).replace([np.inf, -np.inf], np.nan).fillna(0.0)
    else:
        history["rolling_growth"] = pd.to_numeric(
            history["rolling_growth"], errors="coerce"
        ).replace([np.inf, -np.inf], np.nan).fillna(0.0)

    return history, ranking, year_col


def select_topics(history, ranking, top_n, min_total_count):
    totals = history.groupby("topic")["topic_count"].sum()
    eligible = totals[totals >= min_total_count].index.tolist()

    if ranking is not None and "topic" in ranking.columns:
        r = ranking.copy()
        r["topic"] = pd.to_numeric(r["topic"], errors="coerce")
        r = r.dropna(subset=["topic"])
        r["topic"] = r["topic"].astype(int)
        r = r[r["topic"].isin(eligible)]
        if "weak_signal_rank" in r.columns:
            r = r.sort_values("weak_signal_rank")
        elif "weak_signal_score" in r.columns:
            r = r.sort_values("weak_signal_score", ascending=False)
        selected = r["topic"].drop_duplicates().head(top_n).tolist()
    else:
        selected = totals.loc[eligible].sort_values(ascending=False).head(top_n).index.tolist()

    if not selected:
        raise ValueError("No topics satisfy the selection conditions.")
    return selected


def enrich(history, ranking, selected, year_col, tail_years):
    x = history[history["topic"].isin(selected)].copy()
    if tail_years > 0:
        max_year = int(x[year_col].max())
        x = x[x[year_col] >= max_year - tail_years + 1].copy()

    # Remove pre-emergence zero years for each topic. Keep zeros after first appearance.
    first_year = (
        x[x["topic_count"] > 0]
        .groupby("topic")[year_col]
        .min()
        .rename("first_active_year")
    )
    x = x.merge(first_year, left_on="topic", right_index=True, how="left")
    x = x[x[year_col] >= x["first_active_year"]].copy()

    if ranking is not None and "topic" in ranking.columns:
        meta_columns = [
            "topic", "topic_name", "representative_words", "weak_signal_rank",
            "weak_signal_score", "novelty", "novelty_norm", "cohesion",
            "cohesion_norm", "persistence", "persistence_norm",
            "weak_signal_candidate"
        ]
        meta_columns = [c for c in meta_columns if c in ranking.columns]
        meta = ranking[meta_columns].copy()
        meta["topic"] = pd.to_numeric(meta["topic"], errors="coerce")
        meta = meta.dropna(subset=["topic"])
        meta["topic"] = meta["topic"].astype(int)
        meta = meta.drop_duplicates("topic")
        x = x.merge(meta, on="topic", how="left")

    if "topic_name" not in x.columns:
        x["topic_name"] = x["topic"].map(lambda n: f"Topic {n}")
    else:
        x["topic_name"] = x["topic_name"].fillna(
            x["topic"].map(lambda n: f"Topic {n}")
        )
    if "representative_words" not in x.columns:
        x["representative_words"] = ""
    else:
        x["representative_words"] = x["representative_words"].fillna("")

    if "weak_signal_score" not in x.columns:
        x["weak_signal_score"] = np.nan
    if "weak_signal_rank" not in x.columns:
        x["weak_signal_rank"] = np.nan
    if "novelty_norm" not in x.columns:
        x["novelty_norm"] = 0.5
    if "cohesion_norm" not in x.columns:
        x["cohesion_norm"] = 0.5

    x["topic_label"] = x.apply(
        lambda r: f"Topic {int(r['topic'])}: {r['topic_name']}", axis=1
    )
    x = x.sort_values(["topic", year_col]).reset_index(drop=True)
    return x


def clip_growth(df, low_q, high_q):
    x = df.copy()
    active = x.loc[x["topic_count"] > 0, "rolling_growth"]
    if len(active) >= 5:
        low = float(active.quantile(low_q))
        high = float(active.quantile(high_q))
        if low >= high:
            low, high = float(active.min()), float(active.max())
    else:
        low, high = float(x["rolling_growth"].min()), float(x["rolling_growth"].max())
    x["growth_plot"] = x["rolling_growth"].clip(lower=low, upper=high)
    x["growth_was_clipped"] = x["rolling_growth"] != x["growth_plot"]
    return x, low, high


def make_interactive(df, year_col, output_html, low, high):
    try:
        import plotly.graph_objects as go
        import plotly.express as px
    except ImportError as e:
        raise RuntimeError("Plotly is required: pip install plotly") from e

    topics = df["topic"].drop_duplicates().tolist()
    palette = px.colors.qualitative.Dark24 + px.colors.qualitative.Light24
    fig = go.Figure()

    for idx, topic in enumerate(topics):
        g = df[df["topic"] == topic].sort_values(year_col)
        color = palette[idx % len(palette)]
        custom = np.column_stack([
            g[year_col], g["topic_count"], g["rolling_growth"],
            g["weak_signal_score"].fillna(-1), g["representative_words"]
        ])
        fig.add_trace(go.Scatter(
            x=g["share"], y=g["growth_plot"], mode="lines+markers",
            name=g["topic_label"].iloc[0],
            line=dict(color=color, width=2),
            marker=dict(
                size=np.clip(6 + np.sqrt(g["topic_count"].to_numpy()) * 2.2, 7, 24),
                color=color,
                line=dict(color="white", width=0.6),
                opacity=0.85,
            ),
            customdata=custom,
            hovertemplate=(
                "<b>%{fullData.name}</b><br>"
                "Year: %{customdata[0]}<br>"
                "Topic share: %{x:.4%}<br>"
                "Rolling growth (raw): %{customdata[2]:.3f}<br>"
                "Topic count: %{customdata[1]:.0f}<br>"
                "Weak signal score: %{customdata[3]:.3f}<br>"
                "Words: %{customdata[4]}<extra></extra>"
            ),
        ))
        # Add endpoint year labels only.
        last = g.iloc[-1]
        fig.add_annotation(
            x=last["share"], y=last["growth_plot"],
            text=f"T{topic} ({int(last[year_col])})", showarrow=False,
            xshift=6, yshift=6, font=dict(size=10, color=color)
        )

    fig.add_hline(y=0, line_dash="dash", line_color="#8799AA", opacity=0.8)
    fig.update_layout(
        title=(
            "Topic Trajectory Map"
            f"<br><sup>Growth display clipped to {low:.3f} ... {high:.3f}; hover shows raw growth</sup>"
        ),
        xaxis_title="Topic share within each year",
        yaxis_title="Rolling growth (log change)",
        template="plotly_dark",
        paper_bgcolor="#071A2E",
        plot_bgcolor="#071A2E",
        legend_title="Topics",
        hovermode="closest",
        width=1350,
        height=850,
        margin=dict(l=80, r=260, t=100, b=80),
    )
    fig.write_html(output_html, include_plotlyjs=True, full_html=True)


def make_animation(df, year_col, output_html, low, high):
    try:
        import plotly.express as px
    except ImportError as e:
        raise RuntimeError("Plotly is required: pip install plotly") from e

    d = df.copy()
    d["bubble_size"] = np.clip(d["topic_count"], 1, None)
    fig = px.scatter(
        d,
        x="share",
        y="growth_plot",
        animation_frame=year_col,
        animation_group="topic",
        size="bubble_size",
        color="weak_signal_score",
        hover_name="topic_label",
        hover_data={
            "topic": True,
            year_col: True,
            "topic_count": True,
            "share": ":.4%",
            "rolling_growth": ":.3f",
            "weak_signal_score": ":.3f",
            "representative_words": True,
            "bubble_size": False,
            "growth_plot": False,
        },
        color_continuous_scale="Turbo",
        size_max=38,
        range_x=[0, max(float(d["share"].max()) * 1.12, 0.001)],
        range_y=[low, high],
        title="Topic Trajectory Animation",
        template="plotly_dark",
    )
    fig.add_hline(y=0, line_dash="dash", line_color="#8799AA")
    fig.update_layout(
        xaxis_title="Topic share within each year",
        yaxis_title="Rolling growth (log change)",
        paper_bgcolor="#071A2E",
        plot_bgcolor="#071A2E",
        width=1250,
        height=800,
    )
    fig.write_html(output_html, include_plotlyjs=True, full_html=True)


def make_static(df, year_col, output_png, label_top_n, low, high):
    import matplotlib.pyplot as plt
    import matplotlib as mpl
    from matplotlib import colors

    topics = df["topic"].drop_duplicates().tolist()
    cmap = mpl.colormaps.get_cmap("turbo")
    norm = colors.Normalize(vmin=0, vmax=max(len(topics) - 1, 1))

    fig, ax = plt.subplots(figsize=(14, 9))
    for i, topic in enumerate(topics):
        g = df[df["topic"] == topic].sort_values(year_col)
        color = cmap(norm(i))
        ax.plot(g["share"], g["growth_plot"], color=color, linewidth=1.7, alpha=0.75)
        sizes = np.clip(20 + np.sqrt(g["topic_count"].to_numpy()) * 11, 25, 260)
        ax.scatter(g["share"], g["growth_plot"], s=sizes, color=[color],
                   edgecolors="white", linewidths=0.45, alpha=0.85)
        # Direction arrow along the final segment.
        if len(g) >= 2:
            a, b = g.iloc[-2], g.iloc[-1]
            ax.annotate("", xy=(b["share"], b["growth_plot"]),
                        xytext=(a["share"], a["growth_plot"]),
                        arrowprops=dict(arrowstyle="->", color=color, lw=1.4))

    ranking = (
        df[["topic", "weak_signal_rank"]].drop_duplicates("topic")
        .sort_values("weak_signal_rank", na_position="last")
    )
    label_topics = ranking["topic"].head(label_top_n).tolist()
    for topic in label_topics:
        g = df[df["topic"] == topic].sort_values(year_col)
        if g.empty:
            continue
        last = g.iloc[-1]
        ax.annotate(
            f"T{topic}", (last["share"], last["growth_plot"]),
            xytext=(5, 6), textcoords="offset points", fontsize=9, weight="bold"
        )

    ax.axhline(0, linestyle="--", linewidth=1, color="gray")
    ax.set_xlabel("Topic share within each year")
    ax.set_ylabel("Rolling growth (log change)")
    ax.set_title("Topic Trajectory Map\nMarker size = topic count; arrows show movement toward the latest year")
    ax.grid(alpha=0.2)
    ax.set_ylim(low, high)
    fig.tight_layout()
    fig.savefig(output_png, dpi=200, bbox_inches="tight")
    plt.close(fig)


def save_processed_data(df, args, low, high):
    summary = (
        df.sort_values(["topic", args.year_column if args.year_column in df.columns else df.columns[0]])
        .groupby("topic")
        .agg(
            topic_name=("topic_name", "first"),
            first_year=("first_active_year", "first"),
            last_year=(df.columns[df.columns.str.lower().isin(["application_year", "filing_year", "publication_year", "year"])][0]
                       if any(df.columns.str.lower().isin(["application_year", "filing_year", "publication_year", "year"])) else "first_active_year", "max"),
            total_count=("topic_count", "sum"),
            latest_share=("share", "last"),
            latest_growth=("rolling_growth", "last"),
            weak_signal_score=("weak_signal_score", "first"),
            weak_signal_rank=("weak_signal_rank", "first"),
        ).reset_index()
    )
    parameters = pd.DataFrame({
        "parameter": ["growth_plot_min", "growth_plot_max", "input_file", "top_n", "tail_years"],
        "value": [low, high, args.input, args.top_n, args.tail_years],
    })
    with pd.ExcelWriter(args.data_output, engine="openpyxl") as writer:
        df.to_excel(writer, sheet_name="Trajectory Data", index=False)
        summary.to_excel(writer, sheet_name="Topic Summary", index=False)
        parameters.to_excel(writer, sheet_name="Parameters", index=False)


def main():
    args = parse_args()
    warnings.filterwarnings("ignore", category=FutureWarning)

    history, ranking, year_col = load_results(args)
    selected = select_topics(history, ranking, args.top_n, args.min_total_count)
    data = enrich(history, ranking, selected, year_col, args.tail_years)
    data, low, high = clip_growth(data, args.growth_clip_low, args.growth_clip_high)

    make_interactive(data, year_col, args.html, low, high)
    if not args.no_animation:
        make_animation(data, year_col, args.animation_html, low, high)
    make_static(data, year_col, args.png, args.label_top_n, low, high)

    # Save without relying on the user-provided year column name in summary logic.
    with pd.ExcelWriter(args.data_output, engine="openpyxl") as writer:
        data.to_excel(writer, sheet_name="Trajectory Data", index=False)
        latest = data.sort_values(year_col).groupby("topic").tail(1).copy()
        latest = latest[[c for c in [
            "topic", "topic_name", year_col, "topic_count", "share", "rolling_growth",
            "weak_signal_score", "weak_signal_rank", "representative_words"
        ] if c in latest.columns]]
        latest.to_excel(writer, sheet_name="Latest Topic Position", index=False)
        pd.DataFrame({
            "parameter": ["growth_plot_min", "growth_plot_max", "input_file", "top_n", "tail_years"],
            "value": [low, high, args.input, args.top_n, args.tail_years],
        }).to_excel(writer, sheet_name="Parameters", index=False)

    print(f"Selected topics: {selected}")
    print(f"Saved interactive map: {args.html}")
    if not args.no_animation:
        print(f"Saved animation: {args.animation_html}")
    print(f"Saved static map: {args.png}")
    print(f"Saved processed data: {args.data_output}")


if __name__ == "__main__":
    main()
