#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""Calculate and visualize yearly Topic centroids from patent_bertopic_results.xlsx.

The Excel workbook generated by patent_bertopic.py contains topic assignments and
texts, but not document embeddings. This script re-encodes the Documents sheet
with the same SentenceTransformer model, calculates Topic x Year centroids in the
original embedding space, and projects all centroids together into one fixed 2-D
UMAP space for comparable trajectories.

Outputs
-------
- yearly_topic_centroid_map.html          interactive centroid trajectories
- yearly_topic_centroid_animation.html    animated yearly centroids
- yearly_topic_centroid_map.png           static trajectories
- yearly_topic_centroid_data.xlsx         coordinates and semantic-shift metrics
- yearly_topic_centroids.npz              original high-dimensional centroids

Examples
--------
python yearly_topic_centroid_map.py --input patent_bertopic_results.xlsx
python yearly_topic_centroid_map.py --input patent_bertopic_results.xlsx ^
  --embedding-model sentence-transformers/all-MiniLM-L6-v2 ^
  --top-n 15 --min-docs-per-centroid 2
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import warnings

import numpy as np
import pandas as pd
from sklearn.metrics.pairwise import cosine_similarity


def parse_args():
    p = argparse.ArgumentParser(
        description="Yearly Topic centroid trajectories from BERTopic Excel output"
    )
    p.add_argument("--input", default="patent_bertopic_results.xlsx")
    p.add_argument("--documents-sheet", default="Documents")
    p.add_argument("--ranking-sheet", default="Weak Signal Ranking")
    p.add_argument("--config", default="analysis_config.json",
                   help="Optional patent_bertopic.py config file")
    p.add_argument("--text-column", default="abstract")
    p.add_argument("--year-column", default="application_year")
    p.add_argument("--topic-column", default="topic")
    p.add_argument("--id-column", default="publication_number")
    p.add_argument("--embedding-model", default=None,
                   help="Model ID/path. If omitted, read from analysis_config.json; otherwise use all-MiniLM-L6-v2")
    p.add_argument("--batch-size", type=int, default=32)
    p.add_argument("--top-n", type=int, default=20,
                   help="Topics selected by Weak Signal Ranking, or total count if ranking is unavailable")
    p.add_argument("--min-total-topic-docs", type=int, default=3)
    p.add_argument("--min-docs-per-centroid", type=int, default=2,
                   help="Minimum documents required for one Topic-Year centroid")
    p.add_argument("--tail-years", type=int, default=0,
                   help="Use only the latest N years; 0 means all years")
    p.add_argument("--umap-neighbors", type=int, default=10)
    p.add_argument("--umap-min-dist", type=float, default=0.1)
    p.add_argument("--seed", type=int, default=42)
    p.add_argument("--html", default="yearly_topic_centroid_map.html")
    p.add_argument("--animation-html", default="yearly_topic_centroid_animation.html")
    p.add_argument("--png", default="yearly_topic_centroid_map.png")
    p.add_argument("--data-output", default="yearly_topic_centroid_data.xlsx")
    p.add_argument("--centroids-output", default="yearly_topic_centroids.npz")
    p.add_argument("--no-animation", action="store_true")
    p.add_argument("--label-top-n", type=int, default=10)
    return p.parse_args()


def resolve_embedding_model(args):
    if args.embedding_model:
        return args.embedding_model, "command line"
    config_path = Path(args.config)
    if config_path.exists():
        try:
            with config_path.open("r", encoding="utf-8") as f:
                config = json.load(f)
            model = config.get("embedding_model")
            if model:
                return model, str(config_path)
        except (OSError, json.JSONDecodeError):
            pass
    return "sentence-transformers/all-MiniLM-L6-v2", "default"


def find_column(df, requested, candidates, label):
    if requested in df.columns:
        return requested
    lower_map = {str(c).lower(): c for c in df.columns}
    for candidate in candidates:
        if candidate.lower() in lower_map:
            return lower_map[candidate.lower()]
    raise ValueError(f"{label} column not found. Available columns: {list(df.columns)}")


def load_documents(args):
    path = Path(args.input)
    if not path.exists():
        raise FileNotFoundError(f"Input file not found: {path}")

    xl = pd.ExcelFile(path, engine="openpyxl")
    if args.documents_sheet not in xl.sheet_names:
        raise ValueError(
            f"Sheet '{args.documents_sheet}' not found. Available: {xl.sheet_names}"
        )

    docs = pd.read_excel(path, sheet_name=args.documents_sheet, engine="openpyxl")
    ranking = None
    if args.ranking_sheet in xl.sheet_names:
        ranking = pd.read_excel(path, sheet_name=args.ranking_sheet, engine="openpyxl")

    text_col = find_column(
        docs, args.text_column,
        ["abstract", "Abstract", "text", "document", "description"],
        "Text"
    )
    year_col = find_column(
        docs, args.year_column,
        ["application_year", "filing_year", "publication_year", "year", "Year"],
        "Year"
    )
    topic_col = find_column(
        docs, args.topic_column,
        ["topic", "Topic", "topic_id", "Topic ID"],
        "Topic"
    )

    docs[text_col] = docs[text_col].fillna("").astype(str).str.strip()
    docs[year_col] = pd.to_numeric(docs[year_col], errors="coerce")
    docs[topic_col] = pd.to_numeric(docs[topic_col], errors="coerce")
    docs = docs[
        (docs[text_col] != "") & docs[year_col].notna() & docs[topic_col].notna()
    ].copy()
    docs[year_col] = docs[year_col].astype(int)
    docs[topic_col] = docs[topic_col].astype(int)
    docs = docs[docs[topic_col] != -1].reset_index(drop=True)

    if args.id_column not in docs.columns:
        docs[args.id_column] = np.arange(1, len(docs) + 1).astype(str)

    if args.tail_years > 0:
        max_year = int(docs[year_col].max())
        docs = docs[docs[year_col] >= max_year - args.tail_years + 1].reset_index(drop=True)

    if docs.empty:
        raise ValueError("No usable documents remain after filtering.")

    return docs, ranking, text_col, year_col, topic_col


def select_topics(docs, ranking, topic_col, top_n, min_total_docs):
    totals = docs.groupby(topic_col).size().sort_values(ascending=False)
    eligible = totals[totals >= min_total_docs].index.tolist()

    if ranking is not None and "topic" in ranking.columns:
        r = ranking.copy()
        r["topic"] = pd.to_numeric(r["topic"], errors="coerce")
        r = r.dropna(subset=["topic"])
        r["topic"] = r["topic"].astype(int)
        r = r[r["topic"].isin(eligible)]
        if "weak_signal_rank" in r.columns:
            r = r.sort_values("weak_signal_rank")
        elif "weak_signal_score" in r.columns:
            r = r.sort_values("weak_signal_score", ascending=False)
        selected = r["topic"].drop_duplicates().head(top_n).tolist()
    else:
        selected = totals.loc[eligible].head(top_n).index.tolist()

    if not selected:
        raise ValueError("No topics satisfy the selection criteria.")
    return selected


def encode_documents(texts, model_name, batch_size):
    try:
        from sentence_transformers import SentenceTransformer
    except ImportError as e:
        raise RuntimeError(
            "sentence-transformers is required: pip install sentence-transformers"
        ) from e

    model = SentenceTransformer(model_name)
    embeddings = model.encode(
        texts,
        batch_size=batch_size,
        show_progress_bar=True,
        normalize_embeddings=True,
        convert_to_numpy=True,
    )
    return np.asarray(embeddings, dtype=np.float32)


def calculate_yearly_centroids(
    docs, embeddings, year_col, topic_col, selected, min_docs_per_centroid
):
    rows = []
    vectors = []

    selected_docs = docs[docs[topic_col].isin(selected)].copy()
    for (topic, year), group in selected_docs.groupby([topic_col, year_col], sort=True):
        indexes = group.index.to_numpy(dtype=int)
        count = len(indexes)
        if count < min_docs_per_centroid:
            continue

        vectors_year = embeddings[indexes]
        centroid = vectors_year.mean(axis=0)
        norm = np.linalg.norm(centroid)
        if norm > 0:
            centroid = centroid / norm

        similarities = cosine_similarity(vectors_year, centroid.reshape(1, -1)).ravel()
        rows.append({
            "topic": int(topic),
            "year": int(year),
            "document_count": int(count),
            "within_year_cohesion": float(similarities.mean()),
            "within_year_cohesion_std": float(similarities.std(ddof=0)),
        })
        vectors.append(centroid.astype(np.float32))

    if not rows:
        raise ValueError(
            "No Topic-Year centroid could be calculated. Reduce --min-docs-per-centroid."
        )

    meta = pd.DataFrame(rows)
    centroid_matrix = np.vstack(vectors)
    return meta, centroid_matrix


def calculate_semantic_shift(meta, centroid_matrix):
    x = meta.copy().reset_index(drop=True)
    x["previous_year"] = np.nan
    x["year_gap"] = np.nan
    x["consecutive_similarity"] = np.nan
    x["semantic_shift"] = np.nan
    x["shift_per_year"] = np.nan
    x["distance_from_first"] = np.nan

    for topic, indexes in x.groupby("topic").groups.items():
        ordered = sorted(indexes, key=lambda i: x.loc[i, "year"])
        first_index = ordered[0]
        first_vector = centroid_matrix[first_index].reshape(1, -1)

        for position, idx in enumerate(ordered):
            current = centroid_matrix[idx].reshape(1, -1)
            first_similarity = float(cosine_similarity(current, first_vector)[0, 0])
            x.loc[idx, "distance_from_first"] = 1.0 - first_similarity

            if position == 0:
                continue
            previous_idx = ordered[position - 1]
            previous = centroid_matrix[previous_idx].reshape(1, -1)
            similarity = float(cosine_similarity(current, previous)[0, 0])
            shift = 1.0 - similarity
            gap = int(x.loc[idx, "year"] - x.loc[previous_idx, "year"])
            x.loc[idx, "previous_year"] = int(x.loc[previous_idx, "year"])
            x.loc[idx, "year_gap"] = gap
            x.loc[idx, "consecutive_similarity"] = similarity
            x.loc[idx, "semantic_shift"] = shift
            x.loc[idx, "shift_per_year"] = shift / gap if gap > 0 else np.nan

    return x


def project_centroids(centroid_matrix, neighbors, min_dist, seed):
    n = len(centroid_matrix)
    if n < 2:
        raise ValueError("At least two Topic-Year centroids are required for plotting.")

    # UMAP requires n_neighbors < number of samples.
    actual_neighbors = max(2, min(neighbors, n - 1)) if n >= 3 else 1

    if n == 2:
        # A deterministic fallback for two points.
        from sklearn.decomposition import PCA
        coords = PCA(n_components=2).fit_transform(centroid_matrix)
        method = "PCA fallback (only 2 centroids)"
    else:
        try:
            from umap import UMAP
        except ImportError as e:
            raise RuntimeError("umap-learn is required: pip install umap-learn") from e
        reducer = UMAP(
            n_neighbors=actual_neighbors,
            n_components=2,
            min_dist=min_dist,
            metric="cosine",
            random_state=seed,
        )
        coords = reducer.fit_transform(centroid_matrix)
        method = f"UMAP(n_neighbors={actual_neighbors}, min_dist={min_dist})"

    return np.asarray(coords), method


def merge_topic_metadata(meta, ranking):
    x = meta.copy()
    if ranking is not None and "topic" in ranking.columns:
        columns = [
            "topic", "topic_name", "representative_words", "weak_signal_rank",
            "weak_signal_score", "novelty", "cohesion", "persistence",
            "weak_signal_candidate"
        ]
        columns = [c for c in columns if c in ranking.columns]
        topic_meta = ranking[columns].copy()
        topic_meta["topic"] = pd.to_numeric(topic_meta["topic"], errors="coerce")
        topic_meta = topic_meta.dropna(subset=["topic"])
        topic_meta["topic"] = topic_meta["topic"].astype(int)
        topic_meta = topic_meta.drop_duplicates("topic")
        x = x.merge(topic_meta, on="topic", how="left")

    if "topic_name" not in x.columns:
        x["topic_name"] = x["topic"].map(lambda n: f"Topic {n}")
    else:
        x["topic_name"] = x["topic_name"].fillna(
            x["topic"].map(lambda n: f"Topic {n}")
        )
    if "representative_words" not in x.columns:
        x["representative_words"] = ""
    else:
        x["representative_words"] = x["representative_words"].fillna("")
    if "weak_signal_score" not in x.columns:
        x["weak_signal_score"] = np.nan
    if "weak_signal_rank" not in x.columns:
        x["weak_signal_rank"] = np.nan

    x["topic_label"] = x.apply(
        lambda r: f"Topic {int(r['topic'])}: {r['topic_name']}", axis=1
    )
    return x


def make_interactive(meta, output_html, projection_method):
    try:
        import plotly.graph_objects as go
        import plotly.express as px
    except ImportError as e:
        raise RuntimeError("Plotly is required: pip install plotly") from e

    topics = meta["topic"].drop_duplicates().tolist()
    palette = px.colors.qualitative.Dark24 + px.colors.qualitative.Light24
    fig = go.Figure()

    for index, topic in enumerate(topics):
        g = meta[meta["topic"] == topic].sort_values("year")
        color = palette[index % len(palette)]
        custom = np.column_stack([
            g["year"], g["document_count"], g["within_year_cohesion"],
            g["semantic_shift"].fillna(-1), g["distance_from_first"],
            g["weak_signal_score"].fillna(-1), g["representative_words"]
        ])
        marker_sizes = np.clip(
            7 + np.sqrt(g["document_count"].to_numpy()) * 2.5, 8, 28
        )
        fig.add_trace(go.Scatter(
            x=g["centroid_x"],
            y=g["centroid_y"],
            mode="lines+markers+text",
            name=g["topic_label"].iloc[0],
            line=dict(color=color, width=2),
            marker=dict(
                size=marker_sizes,
                color=g["year"],
                colorscale="Viridis",
                line=dict(color="white", width=0.6),
                opacity=0.9,
                showscale=False,
            ),
            text=g["year"].astype(str),
            textposition="top center",
            textfont=dict(size=9, color=color),
            customdata=custom,
            hovertemplate=(
                "<b>%{fullData.name}</b><br>"
                "Year: %{customdata[0]}<br>"
                "Documents: %{customdata[1]}<br>"
                "Within-year cohesion: %{customdata[2]:.3f}<br>"
                "Shift from previous centroid: %{customdata[3]:.4f}<br>"
                "Distance from first centroid: %{customdata[4]:.4f}<br>"
                "Weak signal score: %{customdata[5]:.3f}<br>"
                "Words: %{customdata[6]}<extra></extra>"
            ),
        ))

    fig.update_layout(
        title=(
            "Yearly Topic Centroid Trajectories"
            f"<br><sup>All Topic-Year centroids projected together: {projection_method}</sup>"
        ),
        xaxis_title="Centroid projection dimension 1",
        yaxis_title="Centroid projection dimension 2",
        template="plotly_dark",
        paper_bgcolor="#071A2E",
        plot_bgcolor="#071A2E",
        legend_title="Topics",
        hovermode="closest",
        width=1400,
        height=900,
        margin=dict(l=70, r=280, t=105, b=65),
    )
    fig.write_html(output_html, include_plotlyjs=True, full_html=True)


def make_animation(meta, output_html, projection_method):
    try:
        import plotly.express as px
    except ImportError as e:
        raise RuntimeError("Plotly is required: pip install plotly") from e

    d = meta.copy()
    d["bubble_size"] = np.clip(d["document_count"], 1, None)
    min_x, max_x = float(d["centroid_x"].min()), float(d["centroid_x"].max())
    min_y, max_y = float(d["centroid_y"].min()), float(d["centroid_y"].max())
    pad_x = max((max_x - min_x) * 0.08, 0.3)
    pad_y = max((max_y - min_y) * 0.08, 0.3)

    fig = px.scatter(
        d,
        x="centroid_x",
        y="centroid_y",
        animation_frame="year",
        animation_group="topic",
        color="topic_label",
        size="bubble_size",
        hover_name="topic_label",
        hover_data={
            "topic": True,
            "year": True,
            "document_count": True,
            "within_year_cohesion": ":.3f",
            "semantic_shift": ":.4f",
            "distance_from_first": ":.4f",
            "representative_words": True,
            "centroid_x": False,
            "centroid_y": False,
            "bubble_size": False,
        },
        size_max=38,
        range_x=[min_x - pad_x, max_x + pad_x],
        range_y=[min_y - pad_y, max_y + pad_y],
        title=f"Yearly Topic Centroid Animation<br><sup>{projection_method}</sup>",
        template="plotly_dark",
    )
    fig.update_layout(
        xaxis_title="Centroid projection dimension 1",
        yaxis_title="Centroid projection dimension 2",
        paper_bgcolor="#071A2E",
        plot_bgcolor="#071A2E",
        width=1300,
        height=830,
        legend_title="Topics",
    )
    fig.write_html(output_html, include_plotlyjs=True, full_html=True)


def make_static(meta, output_png, label_top_n, projection_method):
    import matplotlib.pyplot as plt
    import matplotlib as mpl
    from matplotlib import colors

    topics = meta["topic"].drop_duplicates().tolist()
    cmap = mpl.colormaps.get_cmap("turbo")
    norm = colors.Normalize(vmin=0, vmax=max(len(topics) - 1, 1))

    fig, ax = plt.subplots(figsize=(14, 10))
    for index, topic in enumerate(topics):
        g = meta[meta["topic"] == topic].sort_values("year")
        color = cmap(norm(index))
        ax.plot(
            g["centroid_x"], g["centroid_y"],
            color=color, linewidth=1.8, alpha=0.78
        )
        sizes = np.clip(
            25 + np.sqrt(g["document_count"].to_numpy()) * 12, 30, 300
        )
        ax.scatter(
            g["centroid_x"], g["centroid_y"],
            s=sizes, c=g["year"], cmap="viridis",
            edgecolors="white", linewidths=0.55, alpha=0.9
        )
        if len(g) >= 2:
            a, b = g.iloc[-2], g.iloc[-1]
            ax.annotate(
                "", xy=(b["centroid_x"], b["centroid_y"]),
                xytext=(a["centroid_x"], a["centroid_y"]),
                arrowprops=dict(arrowstyle="->", color=color, lw=1.5)
            )

    ranks = (
        meta[["topic", "weak_signal_rank"]]
        .drop_duplicates("topic")
        .sort_values("weak_signal_rank", na_position="last")
    )
    label_topics = ranks["topic"].head(label_top_n).tolist()
    for topic in label_topics:
        g = meta[meta["topic"] == topic].sort_values("year")
        if g.empty:
            continue
        last = g.iloc[-1]
        ax.annotate(
            f"T{topic} ({int(last['year'])})",
            (last["centroid_x"], last["centroid_y"]),
            xytext=(6, 7), textcoords="offset points",
            fontsize=9, weight="bold"
        )

    ax.set_xlabel("Centroid projection dimension 1")
    ax.set_ylabel("Centroid projection dimension 2")
    ax.set_title(
        "Yearly Topic Centroid Trajectories\n"
        f"{projection_method}; marker size = document count; color = year"
    )
    ax.grid(alpha=0.2)
    fig.tight_layout()
    fig.savefig(output_png, dpi=200, bbox_inches="tight")
    plt.close(fig)


def save_outputs(meta, centroid_matrix, args, model_name, model_source, projection_method):
    topic_summary = (
        meta.sort_values(["topic", "year"])
        .groupby("topic")
        .agg(
            topic_name=("topic_name", "first"),
            first_centroid_year=("year", "min"),
            latest_centroid_year=("year", "max"),
            centroid_years=("year", "count"),
            total_documents=("document_count", "sum"),
            mean_cohesion=("within_year_cohesion", "mean"),
            mean_shift=("semantic_shift", "mean"),
            maximum_shift=("semantic_shift", "max"),
            latest_distance_from_first=("distance_from_first", "last"),
            weak_signal_score=("weak_signal_score", "first"),
            weak_signal_rank=("weak_signal_rank", "first"),
        ).reset_index()
    )
    parameters = pd.DataFrame({
        "parameter": [
            "input", "embedding_model", "model_source", "projection_method",
            "min_docs_per_centroid", "top_n", "tail_years", "seed"
        ],
        "value": [
            args.input, model_name, model_source, projection_method,
            args.min_docs_per_centroid, args.top_n, args.tail_years, args.seed
        ]
    })

    with pd.ExcelWriter(args.data_output, engine="openpyxl") as writer:
        meta.to_excel(writer, sheet_name="Yearly Centroid Coordinates", index=False)
        topic_summary.to_excel(writer, sheet_name="Topic Shift Summary", index=False)
        parameters.to_excel(writer, sheet_name="Parameters", index=False)

    np.savez_compressed(
        args.centroids_output,
        centroids=centroid_matrix,
        topic=meta["topic"].to_numpy(dtype=int),
        year=meta["year"].to_numpy(dtype=int),
        document_count=meta["document_count"].to_numpy(dtype=int),
        embedding_model=np.array([model_name]),
    )


def main():
    args = parse_args()
    warnings.filterwarnings("ignore", category=FutureWarning)
    np.random.seed(args.seed)

    model_name, model_source = resolve_embedding_model(args)
    docs, ranking, text_col, year_col, topic_col = load_documents(args)
    selected = select_topics(
        docs, ranking, topic_col, args.top_n, args.min_total_topic_docs
    )
    docs = docs[docs[topic_col].isin(selected)].reset_index(drop=True)

    print(f"Embedding model: {model_name} (source: {model_source})")
    print(f"Documents to encode: {len(docs):,}")
    print(f"Selected topics: {selected}")

    embeddings = encode_documents(
        docs[text_col].tolist(), model_name, args.batch_size
    )
    meta, centroid_matrix = calculate_yearly_centroids(
        docs, embeddings, year_col, topic_col, selected,
        args.min_docs_per_centroid
    )
    meta = calculate_semantic_shift(meta, centroid_matrix)
    coords, projection_method = project_centroids(
        centroid_matrix, args.umap_neighbors, args.umap_min_dist, args.seed
    )
    meta["centroid_x"] = coords[:, 0]
    meta["centroid_y"] = coords[:, 1]
    meta = merge_topic_metadata(meta, ranking)

    make_interactive(meta, args.html, projection_method)
    if not args.no_animation:
        make_animation(meta, args.animation_html, projection_method)
    make_static(meta, args.png, args.label_top_n, projection_method)
    save_outputs(
        meta, centroid_matrix, args, model_name, model_source, projection_method
    )

    print(f"Topic-Year centroids: {len(meta):,}")
    print(f"Saved interactive map: {args.html}")
    if not args.no_animation:
        print(f"Saved animation: {args.animation_html}")
    print(f"Saved static map: {args.png}")
    print(f"Saved metrics: {args.data_output}")
    print(f"Saved original centroids: {args.centroids_output}")


if __name__ == "__main__":
    main()
