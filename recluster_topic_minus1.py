#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""Re-cluster BERTopic Topic -1 documents.

Input:
  patent_bertopic_results.xlsx generated by patent_bertopic.py
  analysis_config.json (optional, to reuse the original embedding model)

Outputs:
  topic_minus1_recluster_results.xlsx
  topic_minus1_recluster_map.html
  topic_minus1_recluster_map.png
  topic_minus1_recluster_model/ (optional)

Purpose:
  Diagnostic / weak-signal exploration. This script does NOT overwrite the
  original BERTopic topic assignments. It looks only inside original Topic -1.
"""
from __future__ import annotations

import argparse
import json
import random
from pathlib import Path
import warnings

import numpy as np
import pandas as pd


PATENT_STOP_WORDS = [
    "invention", "present", "method", "system", "device", "unit",
    "apparatus", "comprising", "comprises", "include", "includes",
    "including", "provided", "configured", "first", "second",
    "plurality", "embodiment", "embodiments", "disclosure", "according",
    "thereof", "therein", "wherein", "said",
    "drone", "drones", "uav", "uavs", "uas", "unmanned", "aerial",
]


def parse_args():
    p = argparse.ArgumentParser(description="Re-cluster original BERTopic Topic -1")
    p.add_argument("--input", default="patent_bertopic_results.xlsx")
    p.add_argument("--documents-sheet", default="Documents")
    p.add_argument("--config", default="analysis_config.json")
    p.add_argument("--text-column", default="embedding_text")
    p.add_argument("--title-column", default="title")
    p.add_argument("--abstract-column", default="abstract")
    p.add_argument("--topic-column", default="topic")
    p.add_argument("--year-column", default="application_year")
    p.add_argument("--id-column", default="publication_number")
    p.add_argument("--embedding-model", default=None)

    # More permissive defaults than the first-stage clustering.
    p.add_argument("--min-topic-size", type=int, default=5)
    p.add_argument("--hdbscan-min-cluster-size", type=int, default=5)
    p.add_argument("--hdbscan-min-samples", type=int, default=2)
    p.add_argument("--umap-neighbors", type=int, default=10)
    p.add_argument("--umap-components", type=int, default=5)
    p.add_argument("--umap-min-dist", type=float, default=0.0)
    p.add_argument("--seed", type=int, default=42)
    p.add_argument("--batch-size", type=int, default=32)
    p.add_argument("--nr-topics", default=None,
                   help="Default None preserves HDBSCAN clusters; use 'auto' if desired")

    p.add_argument("--output", default="topic_minus1_recluster_results.xlsx")
    p.add_argument("--html", default="topic_minus1_recluster_map.html")
    p.add_argument("--png", default="topic_minus1_recluster_map.png")
    p.add_argument("--model-dir", default="topic_minus1_recluster_model")
    p.add_argument("--no-save-model", action="store_true")
    return p.parse_args()


def resolve_embedding_model(args):
    if args.embedding_model:
        return args.embedding_model, "command line"

    config_path = Path(args.config)
    if config_path.exists():
        try:
            with config_path.open("r", encoding="utf-8") as f:
                config = json.load(f)
            model = config.get("embedding_model")
            if model:
                return model, str(config_path)
        except (OSError, json.JSONDecodeError):
            pass

    return "sentence-transformers/all-MiniLM-L6-v2", "default"


def load_outliers(args):
    path = Path(args.input)
    if not path.exists():
        raise FileNotFoundError(f"Input file not found: {path}")

    df = pd.read_excel(path, sheet_name=args.documents_sheet, engine="openpyxl")

    if args.topic_column not in df.columns:
        raise ValueError(
            f"Topic column '{args.topic_column}' not found. Available: {list(df.columns)}"
        )

    df[args.topic_column] = pd.to_numeric(df[args.topic_column], errors="coerce")
    outliers = df[df[args.topic_column] == -1].copy()

    if outliers.empty:
        raise ValueError("No original Topic -1 documents were found.")

    # Prefer the exact embedding text used by the revised patent_bertopic.py.
    if args.text_column in outliers.columns:
        outliers["recluster_text"] = (
            outliers[args.text_column].fillna("").astype(str).str.strip()
        )
    else:
        # Backward-compatible fallback for older result files.
        missing = [
            c for c in [args.title_column, args.abstract_column]
            if c not in outliers.columns
        ]
        if missing:
            raise ValueError(
                f"'{args.text_column}' is absent and fallback columns are missing: {missing}"
            )
        title = outliers[args.title_column].fillna("").astype(str).str.strip()
        abstract = outliers[args.abstract_column].fillna("").astype(str).str.strip()
        outliers["recluster_text"] = [
            ". ".join(part for part in (t, a) if part)
            for t, a in zip(title, abstract)
        ]

    before = len(outliers)
    outliers = outliers[outliers["recluster_text"] != ""].copy()
    outliers.reset_index(drop=True, inplace=True)
    removed = before - len(outliers)
    if removed:
        print(f"Warning: removed {removed} Topic -1 records with empty text.")

    if outliers.empty:
        raise ValueError("No usable Topic -1 documents remain after text cleaning.")

    return outliers


def build_recluster_model(args, model_name):
    try:
        from bertopic import BERTopic
        from sentence_transformers import SentenceTransformer
        from umap import UMAP
        from hdbscan import HDBSCAN
        from sklearn.feature_extraction.text import CountVectorizer, ENGLISH_STOP_WORDS
    except ImportError as e:
        raise RuntimeError(
            "Missing packages. Install BERTopic, sentence-transformers, umap-learn, "
            "hdbscan and scikit-learn."
        ) from e

    embedding_model = SentenceTransformer(model_name)

    umap_model = UMAP(
        n_neighbors=args.umap_neighbors,
        n_components=args.umap_components,
        min_dist=args.umap_min_dist,
        metric="cosine",
        random_state=args.seed,
    )

    hdbscan_model = HDBSCAN(
        min_cluster_size=args.hdbscan_min_cluster_size,
        min_samples=args.hdbscan_min_samples,
        metric="euclidean",
        cluster_selection_method="eom",
        prediction_data=True,
    )

    custom_stop_words = sorted(set(ENGLISH_STOP_WORDS) | set(PATENT_STOP_WORDS))
    vectorizer_model = CountVectorizer(stop_words=custom_stop_words)

    nr_topics = args.nr_topics
    if isinstance(nr_topics, str) and nr_topics.lower() == "none":
        nr_topics = None

    topic_model = BERTopic(
        embedding_model=embedding_model,
        umap_model=umap_model,
        hdbscan_model=hdbscan_model,
        vectorizer_model=vectorizer_model,
        min_topic_size=args.min_topic_size,
        nr_topics=nr_topics,
        calculate_probabilities=False,
        verbose=True,
    )

    return topic_model, embedding_model


def get_topic_words(topic_model, topic, n=12):
    values = topic_model.get_topic(int(topic)) or []
    return ", ".join(word for word, _ in values[:n])


def build_topic_summary(outliers, topic_model, year_col):
    info = topic_model.get_topic_info().copy()
    info = info.rename(columns={"Topic": "subtopic", "Count": "document_count"})

    if "subtopic" not in info.columns:
        return info

    info["representative_words"] = info["subtopic"].apply(
        lambda t: get_topic_words(topic_model, t)
    )

    if year_col in outliers.columns:
        years = outliers.copy()
        years[year_col] = pd.to_numeric(years[year_col], errors="coerce")
        year_summary = (
            years[years["recluster_topic"] != -1]
            .dropna(subset=[year_col])
            .groupby("recluster_topic")[year_col]
            .agg(first_year="min", last_year="max", active_years="nunique")
            .reset_index()
            .rename(columns={"recluster_topic": "subtopic"})
        )
        info = info.merge(year_summary, on="subtopic", how="left")

    total = len(outliers)
    info["share_of_original_outliers"] = info["document_count"] / total
    return info


def make_year_table(outliers, year_col):
    if year_col not in outliers.columns:
        return pd.DataFrame()

    x = outliers.copy()
    x[year_col] = pd.to_numeric(x[year_col], errors="coerce")
    x = x.dropna(subset=[year_col])
    if x.empty:
        return pd.DataFrame()

    x[year_col] = x[year_col].astype(int)
    table = (
        x.groupby([year_col, "recluster_topic"])
        .size()
        .rename("document_count")
        .reset_index()
    )
    totals = x.groupby(year_col).size().rename("original_outlier_total").reset_index()
    table = table.merge(totals, on=year_col, how="left")
    table["share_within_original_outliers"] = (
        table["document_count"] / table["original_outlier_total"]
    )
    return table


def project_for_visualization(embeddings, topics, seed):
    from umap import UMAP

    n = len(embeddings)
    neighbors = min(15, max(2, n - 1))
    reducer = UMAP(
        n_neighbors=neighbors,
        n_components=2,
        min_dist=0.1,
        metric="cosine",
        random_state=seed,
    )
    xy = reducer.fit_transform(embeddings)
    return xy


def make_maps(outliers, embeddings, args):
    import matplotlib.pyplot as plt
    import matplotlib as mpl
    import plotly.express as px

    xy = project_for_visualization(embeddings, outliers["recluster_topic"].to_numpy(), args.seed)
    plot_df = outliers.copy()
    plot_df["x"] = xy[:, 0]
    plot_df["y"] = xy[:, 1]
    plot_df["subtopic_label"] = plot_df["recluster_topic"].apply(
        lambda t: "Residual -1" if int(t) == -1 else f"Subtopic {int(t)}"
    )

    hover_cols = [c for c in [
        args.id_column, args.title_column, args.year_column,
        "recluster_topic", "subtopic_words"
    ] if c in plot_df.columns]

    fig = px.scatter(
        plot_df,
        x="x",
        y="y",
        color="subtopic_label",
        hover_data=hover_cols,
        title="Re-clustering of Original BERTopic Topic -1",
        template="plotly_dark",
        opacity=0.72,
    )
    fig.update_layout(width=1350, height=850)
    fig.write_html(args.html, include_plotlyjs=True, full_html=True)

    topics = sorted(plot_df["recluster_topic"].unique())
    cmap = mpl.colormaps.get_cmap("turbo")
    colors = {t: (0.55, 0.55, 0.55, 0.45) if t == -1 else cmap(i / max(len(topics)-1, 1))
              for i, t in enumerate(topics)}

    fig2, ax = plt.subplots(figsize=(13, 9))
    for t in topics:
        g = plot_df[plot_df["recluster_topic"] == t]
        label = "Residual -1" if t == -1 else f"Subtopic {t}"
        ax.scatter(g["x"], g["y"], s=12, alpha=0.62, color=[colors[t]], label=label)
    ax.set_title("Re-clustering of Original BERTopic Topic -1")
    ax.set_xlabel("UMAP dimension 1")
    ax.set_ylabel("UMAP dimension 2")
    ax.grid(alpha=0.15)
    if len(topics) <= 25:
        ax.legend(loc="best", fontsize=8)
    fig2.tight_layout()
    fig2.savefig(args.png, dpi=200, bbox_inches="tight")
    plt.close(fig2)

    return plot_df


def main():
    args = parse_args()
    random.seed(args.seed)
    np.random.seed(args.seed)
    warnings.filterwarnings("ignore", category=FutureWarning)

    outliers = load_outliers(args)
    model_name, model_source = resolve_embedding_model(args)

    print(f"Original Topic -1 documents: {len(outliers):,}")
    print(f"Embedding model: {model_name} (source: {model_source})")

    topic_model, embedding_model = build_recluster_model(args, model_name)

    docs = outliers["recluster_text"].tolist()
    embeddings = embedding_model.encode(
        docs,
        batch_size=args.batch_size,
        show_progress_bar=True,
        normalize_embeddings=True,
        convert_to_numpy=True,
    )

    print("Re-clustering original Topic -1...")
    subtopics, _ = topic_model.fit_transform(docs, embeddings)
    outliers["recluster_topic"] = np.asarray(subtopics, dtype=int)
    outliers["subtopic_words"] = outliers["recluster_topic"].apply(
        lambda t: get_topic_words(topic_model, t)
    )

    total = len(outliers)
    residual = int((outliers["recluster_topic"] == -1).sum())
    assigned = total - residual
    cluster_count = int(outliers.loc[outliers["recluster_topic"] != -1, "recluster_topic"].nunique())

    summary = build_topic_summary(outliers, topic_model, args.year_column)
    year_table = make_year_table(outliers, args.year_column)
    plot_df = make_maps(outliers, embeddings, args)

    diagnostics = pd.DataFrame({
        "metric": [
            "original_topic_minus1_documents",
            "reclustered_into_subtopics",
            "residual_topic_minus1",
            "reclustered_share",
            "residual_share",
            "number_of_subtopics",
            "embedding_model",
            "embedding_model_source",
            "hdbscan_min_cluster_size",
            "hdbscan_min_samples",
            "umap_neighbors",
            "umap_components",
            "umap_min_dist",
        ],
        "value": [
            total, assigned, residual,
            assigned / total if total else np.nan,
            residual / total if total else np.nan,
            cluster_count,
            model_name, model_source,
            args.hdbscan_min_cluster_size,
            args.hdbscan_min_samples,
            args.umap_neighbors,
            args.umap_components,
            args.umap_min_dist,
        ],
    })

    with pd.ExcelWriter(args.output, engine="openpyxl") as writer:
        outliers.to_excel(writer, sheet_name="Reclustered Documents", index=False)
        summary.to_excel(writer, sheet_name="Subtopic Summary", index=False)
        if not year_table.empty:
            year_table.to_excel(writer, sheet_name="Subtopic by Year", index=False)
        diagnostics.to_excel(writer, sheet_name="Diagnostics", index=False)
        plot_df[[c for c in [args.id_column, "recluster_topic", "x", "y"] if c in plot_df.columns]].to_excel(
            writer, sheet_name="Map Coordinates", index=False
        )

    if not args.no_save_model:
        try:
            topic_model.save(args.model_dir, serialization="safetensors", save_ctfidf=True)
        except Exception as e:
            print(f"Warning: model save failed: {e}")

    print("\n===== Re-clustering summary =====")
    print(f"Original Topic -1: {total:,}")
    print(f"Assigned to new subtopics: {assigned:,} ({assigned/total:.1%})")
    print(f"Residual -1: {residual:,} ({residual/total:.1%})")
    print(f"New subtopics: {cluster_count}")
    print(f"Saved: {args.output}")
    print(f"Saved: {args.html}")
    print(f"Saved: {args.png}")


if __name__ == "__main__":
    main()
